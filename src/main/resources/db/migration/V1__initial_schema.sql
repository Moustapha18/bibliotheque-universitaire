
-- Module catalogue : catégories, ouvrages et exemplaires
CREATE TABLE categories (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            nom VARCHAR(100) NOT NULL UNIQUE,
                            description VARCHAR(500)
);

CREATE TABLE ouvrages (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          titre VARCHAR(200) NOT NULL,
                          auteur VARCHAR(150) NOT NULL,
                          isbn VARCHAR(20) UNIQUE,
                          annee_publication INTEGER,
                          categorie_id BIGINT NOT NULL REFERENCES categories(id),
                          CONSTRAINT chk_annee_publication
                              CHECK (annee_publication IS NULL OR annee_publication > 0)
);

CREATE TABLE exemplaires (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             code_barre VARCHAR(50) NOT NULL UNIQUE,
                             ouvrage_id BIGINT NOT NULL REFERENCES ouvrages(id),
                             etat VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
                             CONSTRAINT chk_etat_exemplaire
                                 CHECK (etat IN ('DISPONIBLE', 'EMPRUNTE', 'RESERVE', 'INDEMNISE'))
);

-- Module acteurs : étudiants et enseignants
CREATE TABLE adherents (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           numero_adherent VARCHAR(30) NOT NULL UNIQUE,
                           nom VARCHAR(100) NOT NULL,
                           prenom VARCHAR(100) NOT NULL,
                           email VARCHAR(180) NOT NULL UNIQUE,
                           type_adherent VARCHAR(20) NOT NULL,
                           actif BOOLEAN NOT NULL DEFAULT TRUE,
                           CONSTRAINT chk_type_adherent
                               CHECK (type_adherent IN ('ETUDIANT', 'ENSEIGNANT'))
);

-- Module transactions : emprunts, réservations et pénalités
CREATE TABLE emprunts (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          exemplaire_id BIGINT NOT NULL REFERENCES exemplaires(id),
                          adherent_id BIGINT NOT NULL REFERENCES adherents(id),
                          date_emprunt DATE NOT NULL,
                          date_retour_prevue DATE NOT NULL,
                          date_retour_effective DATE,
                          CONSTRAINT chk_dates_emprunt
                              CHECK (date_retour_prevue >= date_emprunt),
                          CONSTRAINT chk_dates_retour
                              CHECK (
                                  date_retour_effective IS NULL
                                      OR date_retour_effective >= date_emprunt
                                  )
);

CREATE UNIQUE INDEX uq_emprunt_actif_exemplaire
    ON emprunts(exemplaire_id)
    WHERE date_retour_effective IS NULL;

CREATE TABLE reservations (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              ouvrage_id BIGINT NOT NULL REFERENCES ouvrages(id),
                              adherent_id BIGINT NOT NULL REFERENCES adherents(id),
                              date_reservation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              statut VARCHAR(20) NOT NULL DEFAULT 'EN_ATTENTE',
                              CONSTRAINT chk_statut_reservation
                                  CHECK (statut IN ('EN_ATTENTE', 'DISPONIBLE', 'ANNULEE', 'HONOREE'))
);

CREATE TABLE penalites (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           emprunt_id BIGINT NOT NULL UNIQUE REFERENCES emprunts(id),
                           montant DECIMAL(10, 2) NOT NULL,
                           payee BOOLEAN NOT NULL DEFAULT FALSE,
                           CONSTRAINT chk_montant_penalite CHECK (montant >= 0)
);

-- Module notifications : historique des notifications
CREATE TABLE notifications (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               adherent_id BIGINT NOT NULL,
                               type_notification VARCHAR(50) NOT NULL,
                               message VARCHAR(1000) NOT NULL,
                               date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               lue BOOLEAN NOT NULL DEFAULT FALSE
);

-- Index utiles aux recherches et aux traitements courants
CREATE INDEX idx_ouvrages_titre ON ouvrages(titre);
CREATE INDEX idx_ouvrages_auteur ON ouvrages(auteur);
CREATE INDEX idx_exemplaires_ouvrage ON exemplaires(ouvrage_id);
CREATE INDEX idx_emprunts_adherent ON emprunts(adherent_id);
CREATE INDEX idx_reservations_file
    ON reservations(ouvrage_id, date_reservation)
    WHERE statut = 'EN_ATTENTE';
CREATE INDEX idx_notifications_adherent
    ON notifications(adherent_id, date_creation);
