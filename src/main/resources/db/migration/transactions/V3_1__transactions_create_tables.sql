-- Pas de clé étrangère vers les tables des autres modules : couplage par identifiant uniquement.
CREATE TABLE emprunt (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adherent_id           BIGINT        NOT NULL,
    exemplaire_id         BIGINT        NOT NULL,
    date_emprunt          DATE          NOT NULL,
    date_retour_prevue    DATE          NOT NULL,
    date_retour_effective DATE,
    jours_retard          INTEGER       NOT NULL DEFAULT 0,
    penalite              NUMERIC(10,2) NOT NULL DEFAULT 0
);

CREATE INDEX idx_emprunt_adherent ON emprunt (adherent_id);
-- Garde-fou en base : au plus un emprunt en cours par exemplaire
CREATE UNIQUE INDEX uk_emprunt_exemplaire_en_cours ON emprunt (exemplaire_id) WHERE date_retour_effective IS NULL;

CREATE TABLE reservation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ouvrage_id       BIGINT      NOT NULL,
    adherent_id      BIGINT      NOT NULL,
    exemplaire_id    BIGINT,
    statut           VARCHAR(20) NOT NULL,
    date_reservation TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_reservation_file ON reservation (ouvrage_id, statut, date_reservation);
CREATE UNIQUE INDEX uk_reservation_exemplaire_prete ON reservation (exemplaire_id) WHERE statut = 'PRETE';
