CREATE TABLE categorie (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom         VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    CONSTRAINT uk_categorie_nom UNIQUE (nom)
);

CREATE TABLE ouvrage (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre             VARCHAR(255) NOT NULL,
    auteur            VARCHAR(255) NOT NULL,
    annee_publication INTEGER,
    categorie_id      BIGINT       NOT NULL,
    CONSTRAINT fk_ouvrage_categorie FOREIGN KEY (categorie_id) REFERENCES categorie (id)
);

CREATE TABLE exemplaire (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_barre  VARCHAR(50) NOT NULL,
    statut      VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
    ouvrage_id  BIGINT      NOT NULL,
    CONSTRAINT uk_exemplaire_code_barre UNIQUE (code_barre),
    CONSTRAINT fk_exemplaire_ouvrage FOREIGN KEY (ouvrage_id) REFERENCES ouvrage (id)
);

CREATE INDEX idx_ouvrage_categorie ON ouvrage (categorie_id);
CREATE INDEX idx_exemplaire_ouvrage_statut ON exemplaire (ouvrage_id, statut);
